-- =============================================================================
-- 02_estructura.sql — Tablas de la aplicación (app Django "formacion")
-- =============================================================================
--
-- Ejecutar conectado COMO EL ROL DE LA APLICACIÓN, no como postgres:
--
--   psql -U control_formacion -h localhost -p 5432 -d control_formacion -f 02_estructura.sql
--
-- ¿Por qué no como postgres? Las tablas pertenecen a quien las crea. Si las
-- crea postgres, Django (que se conecta como control_formacion) no podrá
-- modificarlas en futuras migraciones. El bloque de comprobación de abajo
-- lo impide.
--
-- Este script reproduce EXACTAMENTE lo que generaría la migración
-- formacion/0001_initial.py de Django (mismos nombres de tablas, columnas,
-- restricciones e índices). Después hay que ejecutar:
--
--   python manage.py migrate --fake-initial
--
-- que crea las tablas internas de Django (usuarios, sesiones...) y marca la
-- 0001 como aplicada en lugar de intentar crear estas tablas otra vez.
--
-- Todo va en una transacción: si algo falla, no se crea nada.
-- =============================================================================

\set ON_ERROR_STOP on

BEGIN;

DO $$
BEGIN
    IF current_user <> 'control_formacion' THEN
        RAISE EXCEPTION
            'Conectado como "%". Ejecuta este script como control_formacion (psql -U control_formacion ...).',
            current_user;
    END IF;
END
$$;


-- -----------------------------------------------------------------------------
-- Catálogos auxiliares
-- -----------------------------------------------------------------------------

CREATE TABLE formacion_sede (
    id      bigint       NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre  varchar(100) NOT NULL
);
-- Único sin distinguir mayúsculas: "Bormujos" y "bormujos" son la misma sede
CREATE UNIQUE INDEX sede_nombre_unico ON formacion_sede (LOWER(nombre));


CREATE TABLE formacion_tipocontrato (
    id      bigint       NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre  varchar(100) NOT NULL
);
CREATE UNIQUE INDEX tipocontrato_nombre_unico ON formacion_tipocontrato (LOWER(nombre));


-- -----------------------------------------------------------------------------
-- Empleados
-- -----------------------------------------------------------------------------

CREATE TABLE formacion_empleado (
    id                 bigint       NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    num_empleado       varchar(20)  NULL UNIQUE,     -- opcional; si se rellena, no se repite
    nombre             varchar(100) NOT NULL,
    apellido1          varchar(100) NOT NULL,
    apellido2          varchar(100) NOT NULL,        -- '' si no tiene segundo apellido
    grupo_profesional  varchar(3)   NOT NULL,        -- 'PAS' o 'PDI' (lo valida Django)
    fecha_antiguedad   date         NOT NULL,
    fecha_baja         date         NULL,            -- NULL = sigue en activo
    sede_id            bigint       NOT NULL,
    contrato_id        bigint       NOT NULL,

    CONSTRAINT empleado_baja_posterior_antiguedad
        CHECK (fecha_baja IS NULL OR fecha_baja >= fecha_antiguedad)
);

-- Claves foráneas. Django las crea DEFERRABLE INITIALLY DEFERRED (se comprueban
-- al hacer COMMIT). Sin ON DELETE, PostgreSQL impide borrar una sede o un
-- contrato que tenga empleados, también desde pgAdmin.
ALTER TABLE formacion_empleado
    ADD CONSTRAINT formacion_empleado_sede_id_5da02d1f_fk_formacion_sede_id
    FOREIGN KEY (sede_id) REFERENCES formacion_sede (id) DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE formacion_empleado
    ADD CONSTRAINT formacion_empleado_contrato_id_0d08bce0_fk_formacion
    FOREIGN KEY (contrato_id) REFERENCES formacion_tipocontrato (id) DEFERRABLE INITIALLY DEFERRED;

-- Índices: Django indexa cada clave foránea, y añade un índice "_like" a los
-- campos de texto únicos para acelerar búsquedas con LIKE 'texto%'.
CREATE INDEX formacion_empleado_num_empleado_d4eac335_like
    ON formacion_empleado (num_empleado varchar_pattern_ops);
CREATE INDEX formacion_empleado_sede_id_5da02d1f     ON formacion_empleado (sede_id);
CREATE INDEX formacion_empleado_contrato_id_0d08bce0 ON formacion_empleado (contrato_id);


-- -----------------------------------------------------------------------------
-- Cursos
-- -----------------------------------------------------------------------------

CREATE TABLE formacion_curso (
    id      bigint       NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nombre  varchar(200) NOT NULL
);
CREATE UNIQUE INDEX curso_nombre_unico ON formacion_curso (LOWER(nombre));


-- -----------------------------------------------------------------------------
-- Formaciones: tabla intermedia Empleado <-> Curso (un curso completado)
-- -----------------------------------------------------------------------------

CREATE TABLE formacion_formacion (
    id                 bigint      NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    nivel              varchar(20) NOT NULL,         -- '' si el curso no tiene niveles
    horas              smallint    NOT NULL CHECK (horas >= 0),  -- Django exige además >= 1
    fecha_realizacion  date        NOT NULL,         -- Django impide fechas futuras
    curso_id           bigint      NOT NULL,
    empleado_id        bigint      NOT NULL,

    -- Un empleado no puede tener dos veces el mismo curso con el mismo nivel
    CONSTRAINT formacion_sin_duplicados UNIQUE (empleado_id, curso_id, nivel)
);

ALTER TABLE formacion_formacion
    ADD CONSTRAINT formacion_formacion_curso_id_776af694_fk_formacion_curso_id
    FOREIGN KEY (curso_id) REFERENCES formacion_curso (id) DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE formacion_formacion
    ADD CONSTRAINT formacion_formacion_empleado_id_07ebfbf7_fk_formacion
    FOREIGN KEY (empleado_id) REFERENCES formacion_empleado (id) DEFERRABLE INITIALLY DEFERRED;

CREATE INDEX formacion_formacion_curso_id_776af694    ON formacion_formacion (curso_id);
CREATE INDEX formacion_formacion_empleado_id_07ebfbf7 ON formacion_formacion (empleado_id);


-- -----------------------------------------------------------------------------
-- Comentarios (visibles en pgAdmin; Django los ignora)
-- -----------------------------------------------------------------------------

COMMENT ON TABLE formacion_sede          IS 'Catálogo de sedes';
COMMENT ON TABLE formacion_tipocontrato  IS 'Catálogo de tipos de contrato';
COMMENT ON TABLE formacion_empleado      IS 'Empleados. Activo = fecha_baja IS NULL';
COMMENT ON TABLE formacion_curso         IS 'Catálogo de cursos (sin nivel: el nivel va en cada formación)';
COMMENT ON TABLE formacion_formacion     IS 'Cursos completados por cada empleado (tabla intermedia)';

COMMIT;

\echo
\echo 'Estructura creada. Siguiente paso, desde backend/:'
\echo '  python manage.py migrate --fake-initial'